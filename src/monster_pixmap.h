/*
 * monster_palette_lookup
 * 2 文字のパレットコードを添字に変換する。未知のコードは 0 (透明)。
 */
static int
monster_palette_lookup(char c0, char c1)
{
	int i;

	for (i = 0; i < MONSTER_PALETTE_SIZE; i++) {
		if (monster_palette_code[i][0] == c0 &&
		    monster_palette_code[i][1] == c1)
			return i;
	}
	return 0;
}

/*
 * monster_pixmap_decode
 * 文字列のドット絵を sd->w * sd->h バイトのパレット添字配列に展開する。
 * out は MONSTER_PIXMAP_MAX_W * MONSTER_PIXMAP_MAX_H バイト以上必要。
 */
static void
monster_pixmap_decode(const struct sprite_def *sd, uint8_t *out)
{
	int x, y;

	for (y = 0; y < sd->h; y++) {
		const char *row = sd->art[y];
		for (x = 0; x < sd->w; x++) {
			char c0 = row[x * 2];
			char c1 = c0 ? row[x * 2 + 1] : '\0';
			out[y * sd->w + x] = (uint8_t)(
			    (c0 && c1) ? monster_palette_lookup(c0, c1) : 0);
		}
	}
}

/*
 * monster_pixmap_nearest
 * 0..100 スケールの RGB に最も近いパレット添字を返す (1 番以降から探す)。
 */
static int
monster_pixmap_nearest(int r, int g, int b)
{
	int best = 1, bd = -1, i;

	for (i = 1; i < MONSTER_PALETTE_SIZE; i++) {
		int dr = monster_palette_rgb[i][0] - r;
		int dg = monster_palette_rgb[i][1] - g;
		int db = monster_palette_rgb[i][2] - b;
		int d = dr * dr + dg * dg + db * db;
		if (bd < 0 || d < bd) {
			bd = d;
			best = i;
		}
	}
	return best;
}

/*
 * monster_pixmap_fit
 * sw x sh のドット絵を dw x dh の領域に収める。
 *
 * MONSTER_FIT_ASPECT: 縦横比を保ち、左右中央・下端に接地させる。余った部分は
 *   透明 (0) のまま残る。ドット絵が 1:2 でセルも 1:2 ならちょうど全面を使う。
 *   セルがそれより縦長なら上に余白が入る。スプライト向け。
 * MONSTER_FIT_FILL: 縦横比を無視して全面に引き伸ばす。透明部分が残らないので
 *   地形タイル向け (セルが 1:2 でなくても隙間ができない)。
 *
 * 縦横比を保ったままセルいっぱいに収める。ドット絵はセルと同じ 1:2 なので、
 * 一般的な端末では余白なしでちょうど埋まる。
 *
 * 拡大は最近傍。色を混ぜないので、ドットの輪郭がかっちり残る (倍率が整数で
 * ないときは一部のドットが 1 ドットぶん太くなるが、ぼけるよりは見やすい)。
 * 縮小は面積加重平均。単純な間引きだと細部が消えてしまうため。
 *
 * MONSTER_FIT_FILL (地形タイル) は縦横比を無視してセル全面に敷く。
 *
 * 透明が過半を占めるドットは透明のままにして、輪郭の外側がにじまないように
 * する。
 */
static void
monster_pixmap_fit(const uint8_t *src, int sw, int sh, uint8_t *dst,
    int dw, int dh, int mode)
{
	int x, y, ox, oy, fw, fh;

	for (y = 0; y < dw * dh; y++)
		dst[y] = 0;
	if (sw <= 0 || sh <= 0 || dw <= 0 || dh <= 0)
		return;

	if (mode == MONSTER_FIT_FILL) {
		for (y = 0; y < dh; y++) {
			int sy = y * sh / dh;
			for (x = 0; x < dw; x++)
				dst[y * dw + x] = src[sy * sw + x * sw / dw];
		}
		return;
	}

	if (dw * sh <= dh * sw) {
		fw = dw;
		fh = sh * dw / sw;
	} else {
		fh = dh;
		fw = sw * dh / sh;
	}
	if (fw < 1)
		fw = 1;
	if (fh < 1)
		fh = 1;
	ox = (dw - fw) / 2;
	oy = dh - fh; /* 床に接地して見えるよう下寄せ */

	if (fw >= sw && fh >= sh) {
		/* 拡大: 最近傍でかっちり */
		for (y = 0; y < fh; y++) {
			int sy = y * sh / fh;

			for (x = 0; x < fw; x++)
				dst[(oy + y) * dw + ox + x] =
				    src[sy * sw + x * sw / fw];
		}
		return;
	}

	/* 座標は「入力 1 ドット = fw (fh) サブ単位」で整数のまま扱う。
	 * 出力 1 ドットが覆う範囲は x 方向 sw サブ単位、y 方向 sh サブ単位なので、
	 * 重みの合計はちょうど sw * sh になる。 */
	for (y = 0; y < fh; y++) {
		int ya = y * sh;
		int yb = (y + 1) * sh;
		int sy0 = ya / fh;
		int sy1 = (yb + fh - 1) / fh;

		if (sy1 > sh)
			sy1 = sh;
		for (x = 0; x < fw; x++) {
			int xa = x * sw;
			int xb = (x + 1) * sw;
			int sx0 = xa / fw;
			int sx1 = (xb + fw - 1) / fw;
			long total = (long)sw * (long)sh;
			long op = 0, r = 0, g = 0, b = 0;
			int sx, sy;

			if (sx1 > sw)
				sx1 = sw;
			for (sy = sy0; sy < sy1; sy++) {
				int ylo = sy * fh;
				int yhi = ylo + fh;
				int wy = (yb < yhi ? yb : yhi) -
				    (ya > ylo ? ya : ylo);

				if (wy <= 0)
					continue;
				for (sx = sx0; sx < sx1; sx++) {
					int xlo = sx * fw;
					int xhi = xlo + fw;
					int wx = (xb < xhi ? xb : xhi) -
					    (xa > xlo ? xa : xlo);
					uint8_t idx;
					long w;

					if (wx <= 0)
						continue;
					idx = src[sy * sw + sx];
					if (!idx)
						continue;
					w = (long)wx * (long)wy;
					op += w;
					r += (long)monster_palette_rgb[idx][0] * w;
					g += (long)monster_palette_rgb[idx][1] * w;
					b += (long)monster_palette_rgb[idx][2] * w;
				}
			}
			if (op * 2 < total)
				continue; /* 透明が過半 */
			dst[(oy + y) * dw + ox + x] = (uint8_t)
			    monster_pixmap_nearest((int)(r / op),
			    (int)(g / op), (int)(b / op));
		}
	}
}

